"""Bundle the fixed Project 004 fictional CSV fixture for the browser."""

import argparse
from datetime import date
import json
from pathlib import Path
import sys


HERE = Path(__file__).resolve().parent
PROPOSAL = HERE.parent.parent / "cybersecurity" / "security-proposal-workspace"
sys.path.insert(0, str(PROPOSAL))

from proposal import SCHEMAS, evaluate, read_csv
from remediation import load_actions


ASSESSMENT_DATE = date(2026, 10, 28)
FRESHNESS_DAYS = 180
# Use the proposed schedule approved for the browser preview. The original
# remediation register continues to document the earlier assessment exercise.
BROWSER_SCHEDULE = {
    'ACT-001': ('Review the client file policy', '2026-12-02'),
    'ACT-002': ('Complete and prioritize the supplier inventory', '2026-12-04'),
    'ACT-003': ('Reconcile and review the software inventory', '2026-12-04'),
    'ACT-004': ('Address shared advertising account risk', '2026-11-23'),
    'ACT-005': ('Collect and link MFA coverage evidence', '2026-11-20'),
    'ACT-006': ('Assign an owner for freelancer access reviews', '2026-11-24'),
    'ACT-007': ('Review staff training evidence', '2026-12-08'),
    'ACT-008': ('Complete backup coverage and test a restore', '2026-11-25'),
    'ACT-009': ('Define a control for correlating alerts', '2026-11-30'),
    'ACT-010': ('Resubmit the incident investigation record', '2026-12-01'),
    'ACT-011': ('Verify the backup integrity review date', '2026-11-27'),
}


def browser_action_plan(data):
    review = evaluate(data, ASSESSMENT_DATE, FRESHNESS_DAYS)
    actions = load_actions((PROPOSAL / "data" / "actions.csv").read_bytes(), review)
    requirements = data["requirements"]
    indexes = {row["requirement_id"]: index for index, row in enumerate(requirements)}
    open_ids = {row["requirement_id"] for row in review if row["gaps"]}
    if {action["requirement_id"] for action in actions} != open_ids or len(actions) != len(open_ids):
        raise ValueError("The browser sample needs one action per open requirement.")
    if {action["action_id"] for action in actions} != BROWSER_SCHEDULE.keys():
        raise ValueError("The browser schedule must match the fictional action register.")

    plan = []
    for action in actions:
        index = indexes[action["requirement_id"]]
        title, due_date = BROWSER_SCHEDULE[action["action_id"]]
        plan.append({
            "requirement_index": index,
            "action_id": action["action_id"],
            "title": title,
            "verification_criteria": action["verification_criteria"],
            "priority": requirements[index]["priority"],
            "owner": action["owner"],
            "due_date": date.fromisoformat(due_date).isoformat(),
        })
    return plan


def render():
    data = {
        kind: read_csv(PROPOSAL / "data" / f"{kind}.csv", kind)
        for kind in SCHEMAS
    }
    sample = {
        "format": "security-proposal-workspace",
        "version": 1,
        "as_of": ASSESSMENT_DATE.isoformat(),
        "max_age_days": FRESHNESS_DAYS,
        "data": data,
        "action_plan": browser_action_plan(data),
    }
    return (
        "// Generated by build_fictional_sample.py from the Project 004 fictional CSVs.\n"
        f"window.SecurityWorkspaceSample = {json.dumps(sample, indent=2)};\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check that the bundle is current without changing it")
    args = parser.parse_args()
    output = HERE / "fictional-sample.js"
    try:
        content = render()
        if args.check:
            if not output.is_file() or output.read_text(encoding="utf-8") != content:
                parser.exit(1, "The browser sample is out of date. Run build_fictional_sample.py.\n")
        else:
            output.write_text(content, encoding="utf-8", newline="\n")
    except (OSError, ValueError) as error:
        parser.exit(2, f"Could not build the fictional sample: {error}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
